-- User Service database. This service owns the users table; no other service reads it. Other services trust the signed
-- token this service issues and never look a user up.
-- password_hash holds a BCrypt hash, never the password. SERVICE is deliberately not a storable role: it is the identity
-- one service uses towards another and cannot be given to a person.
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(100)             NOT NULL,
    password_hash VARCHAR(255)             NOT NULL,
    role          VARCHAR(30)              NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    -- the unique constraint is also the index that login and "get user by username" use
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT ck_users_role CHECK (role IN ('CLAIMANT', 'OFFICER', 'MANAGER', 'ADMIN'))
);
