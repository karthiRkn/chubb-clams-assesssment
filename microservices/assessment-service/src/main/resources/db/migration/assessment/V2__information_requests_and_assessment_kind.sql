-- 1. The assessment history becomes a complete record of what an officer did, not only the notes written at review:
--    kind says what each entry is. Existing rows are review notes. A decision (APPROVED or REJECTED) and a settlement
--    (SETTLED) are recorded as entries too, with the officer who did them. Still append-only.
ALTER TABLE claim_assessments ADD COLUMN kind VARCHAR(20) DEFAULT 'NOTE' NOT NULL;
ALTER TABLE claim_assessments ADD CONSTRAINT ck_claim_assessments_kind CHECK (kind IN ('NOTE', 'APPROVED', 'REJECTED', 'SETTLED'));

-- 2. Information requests: a question from an officer to the claimant, and the claimant's answer. They used to live in a
--    separate Information Service with its own database; the Assessment Service now owns them, because asking for
--    information is part of assessing a claim and the review has to know whether a request is still OPEN.
--    A request points to its claim by the claim's public claim_id only. There is no foreign key because the claims table
--    belongs to the Claim Service and lives in a different database; the Claim Service is asked whether a claim exists.
--    Nothing is copied from the old Information Service's database: this is a fresh table (see README, "What changed").
CREATE SEQUENCE information_request_number_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE information_requests (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    information_request_id   VARCHAR(32)   NOT NULL,
    claim_id                 VARCHAR(32)   NOT NULL,
    question                 VARCHAR(2000) NOT NULL,
    status                   VARCHAR(20)   NOT NULL,
    requested_by_officer_id  VARCHAR(50)   NOT NULL,
    created_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    answer                   VARCHAR(4000),
    answered_at              TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_information_requests_public_id UNIQUE (information_request_id),
    CONSTRAINT ck_information_requests_status CHECK (status IN ('OPEN', 'ANSWERED'))
);

-- Listing a claim's requests and counting its OPEN ones (the review check).
CREATE INDEX idx_information_requests_claim_status ON information_requests (claim_id, status);
