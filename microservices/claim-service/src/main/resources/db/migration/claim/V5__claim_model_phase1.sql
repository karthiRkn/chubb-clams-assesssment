-- Phase 1 claim model. Everything here is one migration so a database is never half way between the old and new model.
-- V1 to V4 are not edited (they may already be applied); this changes the result of them.
--
-- 1. Statuses. AWAITING_INFORMATION is renamed MORE_INFO_REQUIRED, and APPROVED is new: an officer now approves a claim
--    (with an approved amount) and settles it as a separate, later step. The old CHECK would refuse the new values, so it
--    is dropped first and put back with all six. Existing claims keep their meaning: only the label of one status changes.
--    The same label is renamed in claim_status_history (the one place history rows are touched: the meaning of every row
--    is unchanged, only the name of that status). A claim that was SETTLED in one step under the old model stays SETTLED,
--    with its former settled amount as its approved amount; its history still reads UNDER_REVIEW to SETTLED, which is
--    exactly what happened.
-- 2. Names that match the documented claim model: description -> incident_description, settled_amount -> approved_amount,
--    created_by -> claimant_id (the claimant's login name from the token; unchanged in meaning and in value).
-- 3. New columns: policy_number (NULL for claims created before it existed; required for every new claim by the API),
--    and who/when settled a claim.
ALTER TABLE claims DROP CONSTRAINT ck_claims_status;

UPDATE claims SET status = 'MORE_INFO_REQUIRED' WHERE status = 'AWAITING_INFORMATION';
UPDATE claim_status_history SET from_status = 'MORE_INFO_REQUIRED' WHERE from_status = 'AWAITING_INFORMATION';
UPDATE claim_status_history SET to_status = 'MORE_INFO_REQUIRED' WHERE to_status = 'AWAITING_INFORMATION';

ALTER TABLE claims ADD CONSTRAINT ck_claims_status
    CHECK (status IN ('SUBMITTED', 'UNDER_REVIEW', 'MORE_INFO_REQUIRED', 'APPROVED', 'REJECTED', 'SETTLED'));

ALTER TABLE claims RENAME COLUMN description TO incident_description;
ALTER TABLE claims RENAME COLUMN settled_amount TO approved_amount;
ALTER TABLE claims RENAME COLUMN created_by TO claimant_id;

ALTER TABLE claims ADD COLUMN policy_number VARCHAR(50);
ALTER TABLE claims ADD COLUMN settled_by_officer_id VARCHAR(50);
ALTER TABLE claims ADD COLUMN settled_at TIMESTAMP WITH TIME ZONE;

-- A claim settled under the old model was decided and settled at the same moment by the same officer.
UPDATE claims SET settled_by_officer_id = decided_by_officer_id, settled_at = decided_at WHERE status = 'SETTLED';

-- "My claims" (GET /api/v1/claims as a claimant) filters on the claimant and sorts newest first.
CREATE INDEX idx_claims_claimant ON claims (claimant_id, created_at);

-- 4. Audit trail of edits a claimant makes to their own claim while it is still SUBMITTED (PATCH /api/v1/claims/{claimId}).
--    Append-only. change_summary has one line per changed field: "field: old -> new" for short values, and "field: changed"
--    for free text (a name, an e-mail address, the description), so personal data is not copied into a second table.
CREATE TABLE claim_update_history (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_pk       BIGINT                   NOT NULL,
    changed_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    actor          VARCHAR(100)             NOT NULL,
    change_summary VARCHAR(4000)            NOT NULL,
    CONSTRAINT fk_update_history_claim FOREIGN KEY (claim_pk) REFERENCES claims (id)
);

-- Listing one claim's edits in order (GET /api/v1/claims/{claimId}/updates).
CREATE INDEX idx_update_history_claim_changed ON claim_update_history (claim_pk, changed_at);
