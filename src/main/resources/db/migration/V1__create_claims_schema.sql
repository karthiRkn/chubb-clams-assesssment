-- Public identifiers come from sequences, which are concurrency-safe (no count+1).
CREATE SEQUENCE claim_number_seq START WITH 101 INCREMENT BY 1;
CREATE SEQUENCE information_request_number_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE claims (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id              VARCHAR(32)   NOT NULL,
    claimant_name         VARCHAR(200)  NOT NULL,
    claimant_email        VARCHAR(254)  NOT NULL,
    market                VARCHAR(2)    NOT NULL,
    claim_type            VARCHAR(20)   NOT NULL,
    description           VARCHAR(2000) NOT NULL,
    incident_date         DATE          NOT NULL,
    claimed_amount        NUMERIC(19,2) NOT NULL,
    currency              VARCHAR(3)    NOT NULL,
    status                VARCHAR(30)   NOT NULL,
    assigned_officer_id   VARCHAR(50),
    decision_reason       VARCHAR(2000),
    settled_amount        NUMERIC(19,2),
    decided_by_officer_id VARCHAR(50),
    decided_at            TIMESTAMP WITH TIME ZONE,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_claims_claim_id UNIQUE (claim_id),
    CONSTRAINT ck_claims_amount_positive CHECK (claimed_amount > 0),
    CONSTRAINT ck_claims_type CHECK (claim_type IN ('MOTOR', 'PROPERTY')),
    CONSTRAINT ck_claims_status CHECK (status IN ('SUBMITTED', 'UNDER_REVIEW', 'AWAITING_INFORMATION', 'SETTLED', 'REJECTED'))
);

-- Officer workload filters (status/market combined, officer, type) and default ordering.
CREATE INDEX idx_claims_status_market ON claims (status, market);
CREATE INDEX idx_claims_assigned_officer ON claims (assigned_officer_id);
CREATE INDEX idx_claims_claim_type ON claims (claim_type);
CREATE INDEX idx_claims_created_at ON claims (created_at);
-- Management summary: outstanding claims grouped by currency / status.
CREATE INDEX idx_claims_status_currency ON claims (status, currency);

CREATE TABLE information_requests (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    information_request_id   VARCHAR(32)   NOT NULL,
    claim_pk                 BIGINT        NOT NULL,
    question                 VARCHAR(2000) NOT NULL,
    status                   VARCHAR(20)   NOT NULL,
    requested_by_officer_id  VARCHAR(50)   NOT NULL,
    created_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    answer                   VARCHAR(4000),
    answered_at              TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_information_requests_public_id UNIQUE (information_request_id),
    CONSTRAINT fk_information_requests_claim FOREIGN KEY (claim_pk) REFERENCES claims (id),
    CONSTRAINT ck_information_requests_status CHECK (status IN ('OPEN', 'ANSWERED'))
);

-- Listing requests for a claim and counting its OPEN ones.
CREATE INDEX idx_information_requests_claim_status ON information_requests (claim_pk, status);
