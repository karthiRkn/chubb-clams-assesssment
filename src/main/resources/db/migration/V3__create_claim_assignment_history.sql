-- Append-only record of every change of a claim's assigned officer (previous assignee, new assignee, when, who).
-- previous_officer_id is NULL for the first assignment. actor is NULL when the request does not say who acted
-- (the assign request carries only the new assignee, and there is no authentication).
CREATE TABLE claim_assignment_history (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_pk            BIGINT                   NOT NULL,
    previous_officer_id VARCHAR(50),
    new_officer_id      VARCHAR(50)              NOT NULL,
    changed_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    actor               VARCHAR(50),
    CONSTRAINT fk_assignment_history_claim FOREIGN KEY (claim_pk) REFERENCES claims (id)
);

-- Listing one claim's assignment history in order (GET /api/v1/claims/{claimId}/assignments).
CREATE INDEX idx_assignment_history_claim_changed ON claim_assignment_history (claim_pk, changed_at);
