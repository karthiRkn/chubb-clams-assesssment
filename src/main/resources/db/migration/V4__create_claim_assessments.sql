-- Assessment notes recorded by an officer when review starts or resumes. Append-only, because a claim can be reviewed
-- more than once (for example again after the claimant answers an information request).
-- officer_id is the officer ID sent in the request; there is no authentication, so it is not a verified identity.
CREATE TABLE claim_assessments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_pk   BIGINT                   NOT NULL,
    officer_id VARCHAR(50)              NOT NULL,
    notes      VARCHAR(2000)            NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_assessments_claim FOREIGN KEY (claim_pk) REFERENCES claims (id)
);

-- Listing one claim's assessment notes in order (GET /api/v1/officer/claims/{claimId}/assessments).
CREATE INDEX idx_assessments_claim_created ON claim_assessments (claim_pk, created_at);
