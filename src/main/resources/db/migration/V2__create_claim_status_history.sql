-- Append-only record of every claim status change (who moved it, from what, to what, when).
-- from_status is NULL for the creation row. Assignment does not change status and is not recorded.
CREATE TABLE claim_status_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_pk    BIGINT                   NOT NULL,
    from_status VARCHAR(30),
    to_status   VARCHAR(30)              NOT NULL,
    changed_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    actor       VARCHAR(50)              NOT NULL,
    CONSTRAINT fk_status_history_claim FOREIGN KEY (claim_pk) REFERENCES claims (id)
);

-- Listing one claim's history in order (GET /api/v1/claims/{claimId}/history).
CREATE INDEX idx_status_history_claim_changed ON claim_status_history (claim_pk, changed_at);
